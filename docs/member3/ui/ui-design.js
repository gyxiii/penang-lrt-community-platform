(() => {
  'use strict';
  const screens = window.MutiaraConnectScreens;
  const $ = id => document.getElementById(id);
  let selected = screens[0];
  let view = 'desktop';
  function render(focus = false) {
    const image = `screenshots/${selected.image}-${view}.png`;
    $('preview-code').textContent = `SCREEN ${selected.code} · ${selected.feature}`;
    $('preview-title').textContent = selected.title;
    $('preview-browser-title').textContent = selected.title;
    $('preview-size').textContent = view === 'desktop' ? '1440 px' : '390 px';
    $('preview-state').textContent = selected.state;
    $('preview-state').className = `ui-label ${selected.state === 'Implemented' ? 'ui-label-live' : 'ui-label-concept'}`;
    $('preview-purpose').textContent = selected.purpose;
    $('preview-action').textContent = selected.action;
    $('preview-notes').textContent = selected.notes;
    $('preview-owner').textContent = selected.owner;
    $('preview-open').href = selected.url;
    $('preview-open').textContent = selected.state === 'Implemented' ? 'Open working screen ↗' : 'Open design prototype ↗';
    $('preview-full').href = image;
    $('preview-image').src = image;
    $('preview-image').alt = `${selected.title} · ${view} · ${selected.state}`;
    $('preview-image').width = view === 'desktop' ? 1440 : 390;
    $('preview-scroll').dataset.view = view;
    $('preview-scroll').scrollTop = 0;
    document.querySelectorAll('[data-screen]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.screen === selected.id)));
    document.querySelectorAll('button[data-view]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.view === view)));
    if (focus) $('screen-preview').focus();
    const url = new URL(location.href);
    url.searchParams.set('screen', selected.id);
    url.searchParams.set('view', view);
    try { history.replaceState(null, '', url); } catch { /* Direct-file browsers may limit history updates. */ }
  }
  screens.forEach(screen => {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'ui-screen-card';
    button.dataset.screen = screen.id;
    button.setAttribute('aria-pressed', 'false');
    const image = document.createElement('img');
    image.src = `screenshots/${screen.image}-desktop.png`;
    image.alt = '';
    image.width = 1440;
    image.loading = 'lazy';
    const imageWrap = document.createElement('span');
    imageWrap.className = 'ui-card-image';
    imageWrap.append(image);
    const info = document.createElement('span');
    info.className = 'ui-card-info';
    const code = document.createElement('span');
    code.className = 'ui-card-code';
    code.textContent = `${screen.code} / ${screen.feature.split(' · ')[0]}`;
    const title = document.createElement('strong');
    title.textContent = screen.title;
    const state = document.createElement('span');
    state.className = `ui-card-state ${screen.state === 'Implemented' ? 'is-live' : 'is-concept'}`;
    state.textContent = screen.state;
    info.append(code, title, state);
    button.append(imageWrap, info);
    button.addEventListener('click', () => { selected = screen; render(true); });
    $('screen-grid').append(button);
  });
  document.querySelectorAll('button[data-view]').forEach(button => button.addEventListener('click', () => { view = button.dataset.view; render(); }));
  const requested = new URLSearchParams(location.search);
  selected = screens.find(screen => screen.id === requested.get('screen')) || screens[0];
  view = requested.get('view') === 'mobile' ? 'mobile' : 'desktop';
  render();
})();
